def envelope(event: str, data: dict[str, Any], event_id: str | None = None) -> str:
    return json.dumps(
        {
            "event": event,
            "id": event_id or new_id(),
            "ts": datetime.now(UTC).isoformat().replace("+00:00", "Z"),
            "data": data,
        },
        ensure_ascii=False,
        default=str,
    )
